#!/bin/sh
# Миграции применяются при старте контейнера (ADR-016).
#
# set -e: если alembic упал, скрипт завершится с ошибкой и до exec дело
# не дойдёт — контейнер не стартует. Работать на старой схеме он не должен.
set -e

echo "[entrypoint] Применяем миграции: alembic upgrade head"
alembic upgrade head
echo "[entrypoint] Миграции применены, запускаем приложение"

exec "$@"
